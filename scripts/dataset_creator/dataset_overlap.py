#!/usr/bin/env python3
r"""Count the Venn-diagram overlaps of the crate datasets.

Usage: dataset_overlap.py [--by-name] [--out-dir DIR] [--tikz TEX] [DATASET_CSV ...]

Each DATASET_CSV has a crate_name,version header. A crate is matched across
datasets on name and version; with --by-name, on name alone (so different
versions of the same crate count as an overlap). Prints the size of every
region of the diagram: crates in exactly that combination of datasets.
With --out-dir, also writes one CSV (crate_name,version) per region there.
With --tikz, also writes the diagram as a tikzpicture for \input into a paper
(three datasets only; the preamble needs tikz and \usetikzlibrary{backgrounds}).

Defaults: ../mirilli-dataset.csv ../capslock-dataset.csv ../treeborrows-dataset.csv
"""
import argparse
import csv
from itertools import combinations
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULTS = ["mirilli-dataset.csv", "capslock-dataset.csv", "treeborrows-dataset.csv"]
TITLES = {"mirilli": "MiriLLI", "capslock": "CapsLock", "treeborrows": "Miri"}

# Three-circle layout, before `scale`: circle colour and centre per dataset,
# title placement per dataset, and count placement per region (by dataset index).
SCALE = 0.78
COLORS = ["blue", "red", "green"]
CENTRES = [(0, 0), (2.4, 0), (1.2, -2)]
TITLE_AT = [("south east", (-0.6, 1.75)), ("south west", (3.0, 1.75)), ("north", (1.2, -4.1))]
COUNT_AT = {
    (0,): (-0.9, 0.5), (1,): (3.3, 0.5), (2,): (1.2, -3.1),
    (0, 1): (1.2, 0.7), (0, 2): (0.0, -1.35), (1, 2): (2.4, -1.35),
    (0, 1, 2): (1.2, -0.67),
}


def label(path):
    return Path(path).stem.removesuffix("-dataset")


def load(path, by_name):
    with open(path, newline="") as f:
        return {r["crate_name"] if by_name else (r["crate_name"], r["version"])
                for r in csv.DictReader(f)}


def tikz(names, sizes, regions, union):
    """Render the three-dataset Venn diagram as a tikzpicture."""
    out = [
        "% Generated by scripts/dataset_creator/dataset_overlap.py; do not edit by hand.",
        "\\begin{tikzpicture}[",
        f"    scale={SCALE},",
        f"    set/.style={{circle, minimum size={4 * SCALE:.2f}cm, draw=#1!70!black, thick,",
        "                fill=#1, fill opacity=0.25, text opacity=1},",
        "    count/.style={font=\\small, align=center},",
        "    title/.style={font=\\bfseries, align=center},",
        "]",
        "  \\begin{scope}[on background layer]",
    ]
    out += [f"    \\node[set={c}] at {xy} {{}};" for c, xy in zip(COLORS, CENTRES)]
    out += ["  \\end{scope}", ""]
    for n, (anchor, xy) in zip(names, TITLE_AT):
        out.append(f"  \\node[title, anchor={anchor}] at {xy} "
                   f"{{{TITLES.get(n, n)}\\\\[-2pt]\\normalfont\\small({sizes[n]:,})}};")
    out.append("")
    for idx, xy in COUNT_AT.items():
        combo = tuple(names[i] for i in idx)
        style = "count, font=\\small\\bfseries" if len(idx) == 3 else "count"
        out.append(f"  \\node[{style}] at {xy} {{{regions[combo]:,}}};  % {' & '.join(combo)}")
    out += ["", f"  \\node[font=\\footnotesize, anchor=north] at (1.2, -5.0) {{union: {union:,} crates}};",
            "\\end{tikzpicture}", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("datasets", nargs="*", default=[HERE.parent / d for d in DEFAULTS])
    ap.add_argument("--by-name", action="store_true", help="match crates on name only")
    ap.add_argument("--out-dir", type=Path, help="write one CSV per region here")
    ap.add_argument("--tikz", type=Path, help="write the Venn diagram as a tikzpicture here")
    args = ap.parse_args()

    names = [label(d) for d in args.datasets]
    if args.tikz and len(names) != 3:
        ap.error("--tikz needs exactly three datasets")
    sets = {n: load(d, args.by_name) for n, d in zip(names, args.datasets)}
    universe = set().union(*sets.values())

    for n in names:
        print(f"{n}: {len(sets[n])} crates")
    print(f"union: {len(universe)} crates\n")

    # Pairwise (and larger) intersections, regardless of the other datasets.
    for k in range(2, len(names) + 1):
        for combo in combinations(names, k):
            inter = set.intersection(*(sets[n] for n in combo))
            print(f"{' & '.join(combo)}: {len(inter)}")
    print()

    # Exclusive regions: in exactly these datasets and none of the others.
    print("exclusive regions:")
    regions = {}
    if args.out_dir:
        args.out_dir.mkdir(parents=True, exist_ok=True)
    for k in range(len(names), 0, -1):
        for combo in combinations(names, k):
            region = {c for c in universe if all(c in sets[n] for n in combo)
                      and not any(c in sets[n] for n in names if n not in combo)}
            regions[combo] = len(region)
            region_name = "+".join(combo) + ("-only" if k == 1 else "")
            print(f"  {region_name}: {len(region)}")
            if args.out_dir:
                with open(args.out_dir / f"{region_name}.csv", "w", newline="") as f:
                    w = csv.writer(f, lineterminator="\n")
                    w.writerow(["crate_name"] if args.by_name else ["crate_name", "version"])
                    w.writerows([c] if args.by_name else c for c in sorted(region))

    if args.tikz:
        args.tikz.write_text(tikz(names, {n: len(sets[n]) for n in names}, regions, len(universe)))
        print(f"\ntikz written to {args.tikz}")


if __name__ == "__main__":
    main()
